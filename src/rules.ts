// The owner's rules and preferences, collected into one file for the AI tools the owner runs by hand
// (Claude Code imports it from ~/.claude/CLAUDE.md, Codex reads it per ~/.codex/AGENTS.md — both wired by
// hand, so noop never touches their files). CLIs with a verified user-level rules file (adapter `rules`)
// get the same content delivered to it automatically, but only when noop owns that file. Rewritten after each sync.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DATA, HOME_DIR } from "./core";
import { CLIS } from "./clis";

export const RULES_FILE = join(HOME_DIR, "rules.md");
const MARKER = "<!-- Generated by Noop";

const section = (dir: string, title: string) => {
  const d = join(DATA, dir);
  if (!existsSync(d)) return "";
  const files = readdirSync(d).filter((f) => f.endsWith(".md")).sort();
  return files.length
    ? `# ${title}\n\n${files.map((f) => `<!-- ${dir}/${f} -->\n${readFileSync(join(d, f), "utf8").trim()}`).join("\n\n")}\n`
    : "";
};

/** Deliver generated rules to one verified CLI's user-level rules file. Never overwrites owner content:
 *  writes only when the file is missing or already Noop-generated (marker line). True when it wrote. */
export function deliverRules(file: string, body: string): boolean {
  const old = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (old === body) return false;
  if (old && !old.startsWith(MARKER)) return false; // the owner's own rules: never touch
  mkdirSync(join(file, ".."), { recursive: true });
  writeFileSync(file, body);
  return true;
}

/** Write rules.md from policies/ and memory/; returns true when it changed. */
export function writeRules(): boolean {
  const body = [
    `${MARKER} from ~/.agent-hub/data (policies/, memory/) after every sync. Edit those files, not this one. -->`,
    section("policies", "Team rules (policies/)"),
    section("memory", "Owner profile and preferences (memory/)"),
  ].filter(Boolean).join("\n\n");
  const old = existsSync(RULES_FILE) ? readFileSync(RULES_FILE, "utf8") : "";
  const changed = old !== body;
  if (changed) {
    mkdirSync(HOME_DIR, { recursive: true });
    writeFileSync(RULES_FILE, body);
  }
  for (const a of CLIS) {
    if (!a.rules || !Bun.which(a.name)) continue; // delivered only to CLIs installed on this machine
    try { deliverRules(a.rules.file(), body); } catch {}
  }
  return changed;
}
